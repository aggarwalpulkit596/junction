// Build the online version.
//   node mp/build.mjs           -> worker/rules.gen.js (Europe server engine) + metro.html + public/ (the static site Cloudflare serves)
//   node mp/build.mjs --engine  -> only the engines (used by the sims)
// The engine is mp/engine.template.js with slices of junction.html spliced in, exactly like tools3d/build.py does for 3D.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rd = (f) => fs.readFileSync(path.join(ROOT, f), 'utf8');
const src = rd('junction.html');
function cut(a, b) {
  const i = src.indexOf(a); if (i < 0) throw new Error(`slice marker missing in junction.html: ${a}`);
  const j = src.indexOf(b, i); if (j < 0) throw new Error(`slice end missing in junction.html: ${b}`);
  return src.slice(i, j).trimEnd() + '\n';
}
const parts = {
  '/*@@DATA@@*/': cut('/* ===== data ===== */', '/* ===== state ===== */'),
  '/*@@PAYMENT@@*/': cut('/* ===== payment ===== */', '/* ===== turn flow ===== */'),
  '/*@@WANTED@@*/': cut('function wanted(p){', 'function botTurn(p){'),
  '/*@@SCORING@@*/': cut('/* ===== scoring ===== */', '/* ===== sheets ===== */'),
};
let eng = rd('mp/engine.template.js');
for (const [k, v] of Object.entries(parts)) {
  if (eng.split(k).length !== 2) throw new Error(`marker ${k} must appear once in mp/engine.template.js`);
  eng = eng.replace(k, () => v);
}
eng = '// GENERATED by `node mp/build.mjs` from mp/engine.template.js + junction.html. Do not edit.\n' + eng;
fs.writeFileSync(path.join(ROOT, 'worker/rules.gen.js'), eng);
console.log('wrote worker/rules.gen.js', eng.split('\n').length, 'lines');

// Junction: Delhi Metro. metro/rules.js is an ES module the Worker imports directly; the browser page gets the same
// code inlined (exports stripped) so solo play runs the identical engine with no build step at runtime.
const inlineModule = (f) => rd(f).replace(/^export (?=(const|let|function|class)\b)/gm, '').replace(/^(import|export) \{[^\n]*\n/gm, '');
const rules = inlineModule('metro/rules.js') + '\n' + inlineModule('metro/live.js');
let metro = rd('metro/metro.template.html');
if (metro.split('/*@@RULES@@*/').length !== 2) throw new Error('marker /*@@RULES@@*/ must appear once in metro/metro.template.html');
metro = metro.replace('/*@@RULES@@*/', () => '/* GENERATED from metro/rules.js + metro/live.js by `node mp/build.mjs`. Edit those files, not this one. */\n' + rules);
fs.writeFileSync(path.join(ROOT, 'metro.html'), '<!-- GENERATED by `node mp/build.mjs` from metro/metro.template.html + metro/rules.js. Do not edit. -->\n' + metro);
console.log('wrote metro.html', metro.split('\n').length, 'lines');

if (!process.argv.includes('--engine')) {
  const out = path.join(ROOT, 'public');
  fs.rmSync(out, { recursive: true, force: true });
  fs.mkdirSync(out, { recursive: true });
  const files = {
    'index.html': 'site/index.html',
    'metro.html': 'metro.html',
    'junction3d.html': 'junction3d.html',
    'junction.html': 'junction.html',
    'junction-saboteur.html': 'junction-saboteur.html',
    'junction3d-saboteur.html': 'junction3d-saboteur.html',
    'favicon.svg': 'site/favicon.svg',
    '_headers': 'site/_headers',
  };
  for (const [to, from] of Object.entries(files)) fs.copyFileSync(path.join(ROOT, from), path.join(out, to));
  console.log('wrote public/:', Object.keys(files).join(', '));
}
